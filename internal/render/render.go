// Package render writes the Lua block. The clipboard helpers are the Omarchy
// implementation: send_key_state with explicit mods, because wtype merges the
// physically held SUPER into the injected chord, and Ctrl+Shift in terminals.
package render

import (
	"fmt"
	"strings"

	"github.com/evandrojr/import-omarchy-key-bindings/internal/planner"
)

// Helpers is emitted at the top of the managed block.
const Helpers = `-- Omarchy-style helpers. Generated by import-omarchy-key-bindings.
local function iokb_ws()
    return (os.getenv("HOME") or "") .. "/.config/hypr/scripts/ryoku-workspace"
end

-- Inject the app's own chord with explicit mods. A virtual keyboard (wtype)
-- cannot do this: the physically held SUPER merges into the injected chord.
local function iokb_send_chord(mods, key)
    hl.dispatch(hl.dsp.send_key_state({ mods = mods, key = key, state = "down" }))
    hl.timer(function()
        hl.dispatch(hl.dsp.send_key_state({ mods = mods, key = key, state = "up" }))
    end, { timeout = 50, type = "oneshot" })
end

local iokb_terminal_classes = {
    "kitty", "alacritty", "ghostty", "foot", "wezterm", "konsole",
    "xterm", "urxvt", "gnome-terminal", "tilix", "terminator",
    "xfce4-terminal", "org.kde.konsole", "com.mitchellh.ghostty",
    "org.wezfurlong.wezterm", "org.codeberg.dnkl.foot",
}

local function iokb_is_terminal()
    local w = hl.get_active_window()
    if not w then
        return false
    end
    for _, tag in ipairs(w.tags or {}) do
        if tag:gsub("%*$", "") == "terminal" then
            return true
        end
    end
    local class = (w.class or w.initial_class or ""):lower()
    for _, name in ipairs(iokb_terminal_classes) do
        if class:find(name, 1, true) then
            return true
        end
    end
    return false
end

local function iokb_clipboard(default_mods, default_key, terminal_mods, terminal_key)
    return function()
        if terminal_mods and iokb_is_terminal() then
            iokb_send_chord(terminal_mods, terminal_key)
        else
            iokb_send_chord(default_mods, default_key)
        end
    end
end`

// Block renders the body that goes between the user.lua markers.
func Block(adds []planner.Add) string {
	var b strings.Builder
	b.WriteString(Helpers)
	b.WriteString("\n")
	for _, a := range adds {
		fmt.Fprintf(&b, "\nhl.bind(%q, %s) -- %s", a.Chord, a.Lua, a.Label)
	}
	return strings.TrimRight(b.String(), "\n")
}
